    private void MUSICtoggleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MUSICtoggleActionPerformed
        // TODO add your handling code here:
        BasicSFXstuff.play();

        if (MUSICtoggle.isSelected()) {
            TitleMusic.setMusictogglevalue(1);
            TitleMusic.stop();
        } else {
            TitleMusic.setMusictogglevalue(0);
            TitleMusic.play();
        }


    }//GEN-LAST:event_MUSICtoggleActionPerformed

